/**
 * 只认最后一次请求的结果.
 *
 * 要解决的问题: 快速连着操作两次(连点两页、换分类的同时回第 1 页、改关键词),
 * 两个请求同时在飞. 谁先回来是不确定的, 而两处的响应处理都是"拿到就赋值" ——
 * 于是**先发的那次后到**, 就会把界面盖成上一个筛选条件的内容. 用户看到的是
 * "我点了 B, 出来的是 A", 而且刷新一下又是对的(因为刷新只有一次请求).
 *
 * 为什么不是 AbortController: 这两处要的是「过期的那次别**写**」, 而不是
 * 「过期的那次别**发**」. 请求已经出去了, 取消对用户没有任何可见收益, 却要多
 * 处理一类 AbortError —— 它和真实失败一样走 catch, 于是 catch 里还得分清
 * "是被我自己取消的"和"是真出错了", 判断反而更多. 序号只有一个判断点,
 * 而且是同步的: await 回来后问一句"我还是最新的那次吗".
 *
 * 【用法上的硬要求】过期分支必须 `return`, 而且要放在**收尾赋值之前**.
 * 两个调用点的结尾都是 `loading.value = false` 这类收尾动作 —— 过期的那次
 * 如果顺手把它执行了, 正在飞的那次就再也关不上(转圈永远不停); 同理, 过期的
 * 那次也不能写 results / error / tagItems / tagTotal.
 *
 * 反过来, 能走到函数末尾就说明没有早退过, 也就是 token 仍是最新的 —— 所以
 * 收尾那行不需要再判一次.
 */
export function useLatestOnly() {
  let seq = 0

  /** 开一次新请求, 返回它的令牌. 调用一次, 之前所有令牌立即作废. */
  const begin = () => ++seq

  /** 这个令牌还是最新的吗 */
  const isCurrent = (token) => token === seq

  return { begin, isCurrent }
}
