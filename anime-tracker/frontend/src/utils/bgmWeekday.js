/**
 * 「今天是星期几」在 Bangumi 日历里的编号 —— 全站只有这一份实现。
 *
 * 为什么值得单独一个文件: 日历是每天一格, 每格的 weekday 长这样
 * `{en:'Mon', cn:'星期一', ja:'月曜日', id:1}`, id 从 1(周一) 到 7(周日);
 * 而 JS 的 `getDay()` 是 0(周日) 到 6(周六) —— 两者差一次换算, 就是下面那一行。
 *
 * 这个换算**曾经错过一次**, 而且错得没有任何征兆: 改前比的是 `cn`, 拿 '周三' 去比
 * 接口回的 '星期三', 字符串对不上, `find` 永远返回 undefined, 「今日放送」整块被
 * `v-if` 藏掉. 没有报错, 也没有任何测试会红 —— 当时的假数据是用被测代码同一个
 * 常量拼的, 两边一起错. 后来首页那个区块加了一条"横向滚动的卡片"用例才把它钓上来.
 *
 * 日期一变它就会红, 所以抄第二份的代价不是"重复 4 行", 而是"同一个坑有两个实现,
 * 而它们会在不同的日子上错". 首页 `Home.vue` 与放送表 `Calendar.vue` 都从这里取。
 */

/** Bangumi 日历的七个格子, 按 id 1..7 排 —— 拿来渲染整周放送表 */
export const BGM_WEEKDAYS = [
  { id: '1', cn: '星期一' },
  { id: '2', cn: '星期二' },
  { id: '3', cn: '星期三' },
  { id: '4', cn: '星期四' },
  { id: '5', cn: '星期五' },
  { id: '6', cn: '星期六' },
  { id: '7', cn: '星期日' },
]

/**
 * 今天是 Bangumi 日历里的第几格(字符串 `"1"`..`"7"`)。
 *
 * 返回**字符串**不是数字, 这不是笔误: 后端把 `weekday` 收成了
 * `Map<String,String>`(见 BangumiDTO.CalendarDay), Jackson 会把 JSON 里的数字 3
 * 强制转成字符串 `"3"` —— 所以 `d.weekday.id` 拿到的是 `"3"`.
 * 只把 cn 换成 id、写成 `=== 3` 是不够的, 那样仍然对不上(与当年那个 bug 同一类:
 * 类型对不上时 `find` 只回 undefined, 不报错).
 */
export function bgmWeekdayId() {
  const dow = new Date().getDay()
  return String(dow === 0 ? 7 : dow)
}
