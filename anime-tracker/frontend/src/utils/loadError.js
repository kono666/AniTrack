/**
 * 把「加载失败」翻译成一句能给用户看的话.
 *
 * 为什么要有这么个小函数: 这批页面(catch 里只 console.error 的那几处)的毛病是
 * **网络错误和空结果长得一模一样** —— 断网、后端 500、超时, 界面上显示的都是
 * 「暂无数据」, 用户以为这个站本来就空, 而不是自己网络断了或者服务挂了.
 * 要分开就得给每一页写错误文案, 而四个页面各写一句必然会飘(有的说「加载失败」,
 * 有的说「请求出错」), 用户的感受是同一个站有两种坏法. 所以文案统一在这里.
 *
 * 三种情况分开说, 因为用户的下一步动作完全不同:
 *   * 服务端回了状态码 -> 是服务端的问题, 重试可能有用, 报出数字便于对日志;
 *   * 超时(axios 的 timeout: 10000) -> 服务端可能在忙, 稍后重试;
 *   * 连不上(请求根本没发出去) -> 先看自己的网络.
 *
 * @param {any}    e      catch 到的错误
 * @param {string} what   正在做什么, 用来拼句子(如「加载番剧」「加载评论」)
 */
export function loadErrorMessage(e, what = '加载') {
  const status = e?.response?.status
  if (status) {
    return `${what}失败：服务端返回 ${status}`
  }
  if (e?.code === 'ECONNABORTED') {
    return `${what}超时，请稍后重试`
  }
  return `${what}失败：连不上服务器，请检查网络后重试`
}
