-- ============================================================================
--  AniTrack · V10 记录「最后一次改密码的时刻」（H2）
--
--  背景：全仓此前**没有任何改密码的入口** —— 用户改不了，管理员也替不了他改。
--  而 config/DataInitializer 创建管理员之后打印的是「请尽快登录并修改初始密码」：
--  代码在给一个不存在的能力打广告。这一版把能力补上，这句话才第一次成立。
--
--  为什么需要这一列，而不是只改 password 就够：
--
--  · JWT 是**无状态**的，本仓的 token 只带 userId（没有 jti），有效期 7 天。改完密码
--    之后旧 token 仍然能被签名校验通过 —— 也就是说「改密码」这件事在服务端等于没发生。
--    而改密码最常见的两个触发点恰恰是「怀疑账号被盗」和「管理员强制重置」，
--    这两件事的全部意义就是**把别人手里的那把钥匙作废**。
--  · 有了这一列，JwtAuthFilter 就能多问一句「这张 token 是改密**之前**签发的吗」。
--    不去引入黑名单：那要么加一份存储、要么让 JWT 变成有状态，而本仓的整套鉴权
--    就是围绕「每次现查库建权限」设计的（见 JwtAuthFilter），多读一列不多花一次查询。
--
--  为什么可空、无默认值：
--
--  · 与 email / failed_attempts 同一条理由 —— 给已有表加 NOT NULL 列，H2 与 PostgreSQL
--    都会因为没有 DEFAULT 子句而拒绝执行（见 V1 的注释与 README「已知限制」）。
--  · 语义上也正好：NULL 读作「从未改过密码」，于是存量用户一个都不会被踢下线。
--    只有真的改过密码的人，才有「改密之前的 token」这种说法。
--
--  为什么是 TIMESTAMP(6) 而不是 TIMESTAMP：与 created_at / updated_at 同一个口径，
--  微秒精度。这里其实只用到**秒**，但全仓时间列统一成 6 位小数，不在这里开特例。
--
--  为什么用 ADD COLUMN IF NOT EXISTS：V2 立下的规矩 —— 每一步都必须可重复执行。
--  这个写法 H2 2.2 与 PostgreSQL 16 都认（本机对两个版本的 H2 各实测过一次）。
--
--  为什么新开 V10 而不是改 V9：已执行过的迁移是历史，只能往后加（同 V1~V9）。
--
--  与 postgres/V10__add_password_changed_at.sql 一一对应（语句逐字相同，用例守着这一点）。
-- ============================================================================

ALTER TABLE "user" ADD COLUMN IF NOT EXISTS password_changed_at TIMESTAMP(6);
