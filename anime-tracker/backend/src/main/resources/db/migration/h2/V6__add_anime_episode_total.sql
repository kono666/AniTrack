-- ============================================================================
--  AniTrack · V6 给 anime 加一列「已完整取回的剧集条数」（H2）
--
--  背景：搜「火影忍者」打开疾风传（subject 2782），官方 500 集，页面只显示 100 集。
--  前端没有截断（就是 v-for 全画），数据本身就只有那么多 —— BangumiApiClient.getEpisodes
--  的 URL 上写着 limit=100，既没有 offset 也没有循环。而接口一直把真实集数报在 total 里
--  （实测 total=500，拿回 100 条，sort 221..320），也就是说这条 URL 从来没读过那个字段。
--
--  修法是按 total 翻页（见 BangumiApiClient.getEpisodes 的注释）。但只改翻页会卡在第二个
--  洞上：AnimeService.getEpisodes 的缓存判据是 !cached.isEmpty() —— 只要本地有一行就当
--  已经取全了。以前"取一页"和"取全"本来就分不出来（存的永远是前 100 条），所以那行看着
--  没毛病；一旦回源能翻页了，它就变成拦路虎：500 集的番第一次仍然只显示改动前存下的那
--  100 条，因为"缓存命中了"。
--
--  所以要能区分"完整取回"与"取了一半"。这一列就是那个标记：只在真的收齐之后，写入那一
--  次收齐的条数。
--
--  为什么不复用 total_episodes（条目接口的声明值，已经在库里）：实测两者会不一致。抽
--  28 部知名长篇逐条比对 total_episodes 与「剧集接口 total(type=0)」，9 部对不上，方向
--  恒为声明值更大：
--    乌龙派出所 373 vs 344   犬夜叉 181 vs 167   食戟之灵 33 vs 24
--    境界的彼方  20 vs 13    进击的巨人 26 vs 25  钢之炼金术师 52 vs 51
--    黑子的篮球  26 vs 25    约会大作战 13 vs 12  辉夜大小姐 15 vs 13
--  （差在哪儿各有各的原因 —— 未播出的预定集、被合并的特别篇等等 —— 都不重要。重要的是
--  拿声明值当"应到"的话，犬夜叉那 167 条永远够不着 181，于是每次打开详情页都要重新下载
--  一遍，比改动前还糟。声明与实际必须分开存，谁也不能替谁作证。）
--
--  为什么 NULL 不加 NOT NULL / 默认值：NULL 是有意义的业务状态 ——「这一行从来没完整取
--  过」，含改动前入库的全部老行。AnimeService 据此决定重取一次，这也就是老数据的自愈
--  路径：用户不用做任何事，点开就修好了。若给个默认值 0，老行会被读成"取过、且确实是
--  空的"，那批截断数据就再也修不回来了。
--
--  为什么 0 也算有效值（而不是当成"没有"）：0 表示"完整取回，确实没有本篇剧集"（只有
--  OP/ED 的条目），它同样值得记下来，否则那种条目每次打开都要再回源一次。
--
--  为什么不建索引：唯一的用法是"取这一行看它取齐没有"，永远按主键单行读，与索引无关。
--  （与 V4 末尾「故意没建的」两条、以及 V5 同一处判断。）
--
--  为什么写 IF NOT EXISTS：这份脚本在一台「Flyway 之前就存在的老库」上也会被执行到
--  （那种库被 baseline 到 1，然后从 V2 起逐个补跑，见 application.yml 里 baseline 那段的
--  注释），而它可能因为历史上手工建过这一列而已经存在。没有 IF NOT EXISTS，那次启动会
--  直接以 "Duplicate column name" 失败。
--
--  为什么新开 V6 而不是改 V1：V1~V5 已在开发库和线上执行过，Flyway 记着校验和 —— 改动
--  已执行脚本的任何一个字节，下次启动都会以 "Migration checksum mismatch" 拒绝启动，
--  唯一的修法是手工去改 flyway_schema_history 表。已经跑过的迁移是历史，只能往后加。
--
--  为什么这次两份脚本逐字相同：ALTER TABLE ... ADD COLUMN IF NOT EXISTS 是 H2 与
--  PostgreSQL 9.6+ 都支持的写法（生产用 PG 16），没有方言差异要绕；INTEGER 在两边也都
--  是同一个类型，不像 V1 里 NUMERIC/DECIMAL 那种驱动报出不同 JDBC 类型码的坑。
--
--  与 postgres/V6__add_anime_episode_total.sql 一一对应（语句逐字相同，用例守着这一点）。
-- ============================================================================

ALTER TABLE anime ADD COLUMN IF NOT EXISTS episode_total INTEGER;
