-- ============================================================================
--  AniTrack · V15 记录「最后一次登录成功的时刻」（PostgreSQL）
--
--  背景、取舍与 H2 那份逐条相同，见 h2/V15__add_user_last_login_at.sql 的头部注释。
--  一句话版本：管理端用户列表答不了「这个号还活着吗」，补一列 last_login_at。
--  可空、无默认，NULL 读作「注册后从未登录过」；**不加索引**（排序第一键是表达式，
--  B-tree 对它无效；要有用得建表达式索引，两方言写法不同）。
--
--  两份脚本的语句逐字相同（用例守着这一点）：ADD COLUMN IF NOT EXISTS 与 TIMESTAMP(6)
--  都是 H2 2.2 与 PostgreSQL 16 双方都认的写法，所以这一版不需要开例外。
-- ============================================================================

ALTER TABLE "user" ADD COLUMN IF NOT EXISTS last_login_at TIMESTAMP(6);
