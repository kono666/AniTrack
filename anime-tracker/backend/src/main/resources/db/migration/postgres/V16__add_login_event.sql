-- ============================================================================
--  AniTrack · V16 「谁在今天来过」——登录事件表（PostgreSQL）
--
--  背景：管理端看板此前是 6 个累计 count()，零时间维度。它能回答「一共多少人」，
--  回答不了「最近有没有人来」—— 后者才是运营真正要看的那个数。而累计值有个很坏的
--  性质：一个再也没人用的站点，累计数会永远停在那个高位上，一路看着都很健康。
--
--  为什么必须新开一张表，而不是拿现成的列凑合：
--
--  · user.last_login_at（V15）只能给出「最后一次」，画不出曲线也数不出 DAU ——
--    一个用户今天来了 20 次和来 1 次，在那一列上完全一样。
--  · 也不拿 user.created_at 当「活跃」：那是注册。批量注册的僵尸号与天天来的老用户，
--    在那一列上恰好是反着排的。
--  · 活跃度天然是**事件**，不是**状态**。把事件塞进状态列里，就是迟早要重算或丢历史。
--    这是本项目第一张「为统计而建」的表，理由要写在这里。
--
--  为什么 user_id 可空：
--
--  · 失败尝试里有一类是**用户名根本不存在**（打错字、或者有人在扫账号）。那种情况
--    没有 user_id 可填，但它恰恰是最该被记下来的那一类。
--  · 可空 + 没有外键（对齐 admin_action_log 的 actor_id）：删用户不该被一串日志挡住，
--    也不该把日志级联删掉 —— 日志的价值恰恰在于它记的是「发生过什么」，
--    而账号是可以后消失的。那一行留下来仍然是一条真实的访问记录。
--
--  为什么不记「尝试的用户名」：
--
--  · 界面上的取舍：那一列存的是**别人随手输进来的字符串**（可能是另一个站点的密码、
--    可能是某人的邮箱），收进来就等于把这些内容长期留在库里。而它换来的信息量，
--    「同一 IP 一分钟里失败了 40 次」这条查询根本不需要用户名就已经给出了。
--  · 需要追查具体账号时，成功事件有 user_id，失败事件有 user_id（用户名存在且密码错）
--    —— 两条路都留着，只有「用户名不存在」这一类是匿名的。
--
--  为什么 created_at 是 NOT NULL 而其余可空：
--
--  · 没有时刻的事件不构成事件，它是这一整张表存在的意义，所以 NOT NULL。
--  · ip 可空：测试与本机直连时取不到有意义的地址，硬塞一个占位值会让「有多少条没有 IP」
--    这个有用的信号消失。长度 45 是 IPv6 文本形式的上限（含 IPv4 映射写法）。
--
--  为什么只建 created_at 一条索引：
--
--  · 看板的三个查询（DAU / WAU / 近 14 天曲线）都是「扫一段时间窗」，保留期清理
--    （DELETE ... WHERE created_at < ?）也是。一条 (created_at) 全部覆盖。
--  · **不建 (user_id, created_at)**：今天没有任何查询是从「某个用户」出发的。按 V4
--    立下的规矩（加索引要有实测依据），它现在只是纯粹的写放大。哪天加了「某个用户的
--    登录历史」再补，那时它会自然成为最左前缀 (user_id, created_at)。
--
--  增长与保留期：
--
--  · 这张表只增不减，一行一个登录事件。按 `anitrack.login-event.retention-days`
--    （默认 180 天）由 LoginEventService 里那条每日定时任务清理，见那里的注释。
--    清理走的就是上面那条索引，不是全表扫。
--
--  为什么用 ADD ... IF NOT EXISTS / CREATE ... IF NOT EXISTS：V2 立下的规矩 ——
--  每一步都必须可重复执行。
--
--  与 h2/V16__add_login_event.sql 一一对应（语句逐字相同，用例守着这一点）。
-- ============================================================================

CREATE TABLE IF NOT EXISTS login_event (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id    BIGINT,
    created_at TIMESTAMP(6) NOT NULL,
    ip         VARCHAR(45),
    success    BOOLEAN      NOT NULL,
    CONSTRAINT pk_login_event PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS idx_login_event_created
    ON login_event (created_at);
