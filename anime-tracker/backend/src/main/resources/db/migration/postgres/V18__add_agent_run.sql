-- ============================================================================
--  AniTrack · V18 Agent 运行记录（PostgreSQL）
--
--  背景：Agent 的轮数、token、每步工具调用与耗时此前**只随回答返回、不落库**。
--  agent_conversation / agent_message 存的是聊天文本，而且访客根本不落库；
--  要做「基线 vs 实验」的对照，必须有一张每次运行都写一行、且能按时间/用户/模型
--  维度统计的表。这是本项目的第二张「为统计而建」的表（第一张是 V16 登录事件）。
--
--  为什么拆两张表（run / step）而不是把工具链塞进一个 JSON 列：
--
--  · 评测要看「第几轮调了什么、耗时多少、有没有失败」，按工具名和轮数过滤是常态；
--    塞进 JSON 后每次都要在应用层展开，既不能建索引，也让 SQL 统计变得难写。
--  · run 一行、step 多行的形状本来就不同，硬塞一张表会出现大量可空列。
--
--  为什么 user_id / conversation_id **不挂外键**：
--
--  · 这是一张测量表，记录的是「发生过什么」。删用户、删会话不应该把历史实验数据
--    一起带走；对齐 V9 账本与 V16 登录事件的判断。
--  · user_id 可空：访客也能对话，他们的运行记录同样有评测价值。
--
--  为什么 run_id 挂 ON DELETE CASCADE：step 离开 run 没有意义，删 run 时一起走；
--  这与 V11 通知的级联是同一个语义。
--
--  增长：一行一次对话，量级远小于登录事件；暂不做保留期清理，评测期需要完整历史。
--
--  与 h2/V18__add_agent_run.sql 一一对应（语句逐字相同，用例守着这一点）。
-- ============================================================================

CREATE TABLE IF NOT EXISTS agent_run (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT,
    conversation_id BIGINT,
    persona         VARCHAR(32)   NOT NULL,
    question        VARCHAR(4000) NOT NULL,
    answer          VARCHAR(8000),
    rounds          INT           NOT NULL,
    input_tokens    INT           NOT NULL,
    output_tokens   INT           NOT NULL,
    total_millis    BIGINT        NOT NULL,
    truncated       BOOLEAN       NOT NULL,
    error           VARCHAR(500),
    trace_id        VARCHAR(64),
    created_at      TIMESTAMP(6)  NOT NULL,
    CONSTRAINT pk_agent_run PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS idx_agent_run_created
    ON agent_run (created_at);

CREATE INDEX IF NOT EXISTS idx_agent_run_user_created
    ON agent_run (user_id, created_at);

CREATE TABLE IF NOT EXISTS agent_run_step (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    run_id         BIGINT        NOT NULL,
    round          INT           NOT NULL,
    tool_name      VARCHAR(64)   NOT NULL,
    arguments      VARCHAR(2000),
    result_preview VARCHAR(2000),
    is_error       BOOLEAN       NOT NULL,
    millis         BIGINT        NOT NULL,
    CONSTRAINT pk_agent_run_step PRIMARY KEY (id),
    CONSTRAINT fk_agent_run_step_run FOREIGN KEY (run_id) REFERENCES agent_run (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_agent_run_step_run
    ON agent_run_step (run_id);
