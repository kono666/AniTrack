package com.animetracker.util;

/**
 * 用户名策略.
 *
 * <p>抽出来的理由与 {@link PasswordPolicy} 相同: 规则有两个使用方(注册接口的
 * 参数校验、前端表单的即时提示), 前端的 JS 没法引用 Java 常量, 只能再写一遍 ——
 * 所以这里必须有一份明确的、可被引用的定义, 而不是把正则散落在注解字符串里.
 *
 * <p><b>为什么需要一个字符集规则.</b> 改前用户名只校验了长度(3-50), 内容是任意
 * 字符. 最直接的问题是冒充: 注册一个 "admin " (尾部一个空格) 或者
 * "admin​" (尾部一个零宽字符), 与已有的 "admin" 是**两个不同的字符串**,
 * 唯一性检查拦不住它们, 而在页面上(评论区的作者名、管理端的用户表、Agent 回答里
 * 引用的用户名)它们看起来一模一样. 这类"看着像同一个人"的账号是社工的起点,
 * 而且事后排查时肉眼分不出差别, 只能去比对码点.
 *
 * <p>除此之外还有两个次要的好处: 控制字符与 bidi 覆盖符(U+202E 那类)不再能进入
 * 一个会被到处渲染、还会进 LLM 上下文的字段; 用户名里也不会再出现空格,
 * 于是一串名字在前端被 split 或者当参数传递时不会莫名其妙地断成两截.
 *
 * <p><b>为什么允许 {@code \p{L}} 而不是 {@code A-Za-z}.</b> 这是个动漫站点,
 * 用户取「绫波丽」「ゆき」这样的名字是常态. 把范围收到 ASCII 会让这批人没法注册,
 * 而规则要防的是"看不见的字符"和"装饰性符号", 不是非拉丁文字.
 * {@code \p{N}} 同理(全角数字、阿拉伯-印度数字都算数字).
 * 下划线与连字符是约定俗成的用户名组成, 一并放行.
 */
public final class UsernamePolicy {

    /** 最短长度. 与 {@code @Size} 里的取值必须一致, 所以那边直接引用这里的常量. */
    public static final int MIN_LENGTH = 3;

    /** 最长长度. 与数据库那一列的宽度对应. */
    public static final int MAX_LENGTH = 50;

    /**
     * 长度不合规时的提示语.
     *
     * <p>由常量拼出来而不是写死「3-50」: 改长度时提示语会跟着变, 不会出现
     * 「提示说 3 位、实际校验 5 位」这种只会被用户发现的不一致.
     * 常量之间拼接仍是编译期常量, 能直接用在注解上.
     */
    public static final String LENGTH_MESSAGE =
            "用户名长度需在 " + MIN_LENGTH + "-" + MAX_LENGTH + " 个字符之间";

    /**
     * 允许的字符: 字母(含中文、日文等)、数字、下划线、连字符.
     *
     * <p>用 {@code ^...$} 和 {@code +} 而不是 {@code find()} 语义: 要求**整个**
     * 字符串都由这些字符组成, 少一个锚点就变成"含有至少一个合法字符就行",
     * 空格与零宽字符又能溜进来 —— 这类正则的错法不会报错, 只会静默放行.
     *
     * <p>不在这里管长度: 那是 {@code @Size} 的职责, 两处都写迟早会不一致.
     * 注意这个正则**不匹配空串**({@code +} 而非 {@code *}), 所以"全是空白"
     * 会落在这条规则上被拒, 而不是通过字符集检查再去撞 @NotBlank 的提示语.
     */
    public static final String REGEX = "^[\\p{L}\\p{N}_-]+$";

    public static final String MESSAGE = "用户名只能包含中文、字母、数字、下划线和连字符";

    private UsernamePolicy() {
    }
}
