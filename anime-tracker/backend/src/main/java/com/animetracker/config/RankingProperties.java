package com.animetracker.config;

import lombok.Data;
import org.springframework.boot.context.properties.ConfigurationProperties;
import org.springframework.stereotype.Component;

/**
 * 排行榜的加权评分参数.
 *
 * <p><b>为什么排行榜不能按评分原值排.</b> Bangumi 的 {@code rating.score} 是一个
 * **平均分**, 它与打分人数完全无关, 于是"1 个人打了 10 分"和"两万个人打出 9.1"被
 * 放在同一个尺度上比较, 前者稳赢. 这不是理论推演, 是实测: 2026-09-29 跑真实模型时,
 * 排行榜前两名是「命运之轮」(评分 10.0, **总共 1 票**) 与「某科学的超电磁炮 第四季」
 * (9.6, **10 票**, 未定档没播). 而 Bangumi 自己的排行算法给这两条都返回
 * {@code rank: 0} —— 意思是**样本不足, 拒绝收录**. 我们等于把对端主动滤掉的噪音
 * 排序后排在了榜首, 并且因为分数确实是 10.0, 界面上看不出任何异常.
 *
 * <p><b>算法是贝叶斯平均</b>(IMDb Top 250 用的那套):
 *
 * <pre>
 *   score = (v / (v + m)) · R  +  (m / (v + m)) · C
 * </pre>
 *
 * v = 打分人数, R = 平均分, m = 先验票数, C = 先验分数. 效果是: 票数越少, 结果越被
 * 拉向 C; 票数远超 m 之后才逐渐靠近自己的 R. 换句话说 <b>m 决定"要多少票才有资格
 * 代表自己的分数", C 决定"没票的时候默认算几分"</b>.
 *
 * <p><b>为什么 m = 200.</b> 实测抽了 Bangumi 浏览接口 offset=0 那 50 条(偏热门的
 * 一段), 票数区间是 253 ~ 34,442, 均分 7.79. 取 m=200 意味着这个区间里的条目基本
 * 已经"摆脱先验": 34,442 票那条算出 8.69(原值 8.7), 19,641 票那条算出 9.08
 * (原值 9.1) —— 大体不动. 而被修的那两条: 1 票 10.0 掉到 **7.01**, 10 票 9.6 掉到
 * **7.12**, 落到榜尾. 也就是说这个 m 的效果是**只掐掉小样本, 不打扰热门条目**.
 * m 调大榜单更稳但更迟钝, 调小冷门更容易冒头 —— 这是产品口味不是正确性, 所以可配.
 *
 * <p><b>为什么 C = 7.0 是个写死的先验, 而不是每次去算库里的 AVG(rating).</b>
 * 均分是个会随数据漂移的量 —— 全量回填三万个条目之后它会变, 于是"同一个榜单"在
 * 数据变了之后会莫名其妙地重排; 而且排行是有缓存的(见
 * {@link com.animetracker.service.AnimeService#getRanking}), 均值一变缓存键却不变,
 * 缓存里存的就是旧口径的结果. 先验取常数之后, 每一行的得分只由它自己的两个数字
 * 决定: 可复现、可解释、可测. 7.0 落在实测热门均分(7.79)之下, 是个偏保守的
 * "及格线"——冷门条目被拉到这里, 排在真正的好番后面.
 *
 * <p><b>为什么单独成类而不是两个散落的 @Value</b>: 与
 * {@link BootstrapProperties} 同一个理由 —— 这两个值只有放在一起才有意义
 * (一个说"多少票算数", 一个说"没票算几分"), 而且上面这段推导需要一个能写下来的
 * 地方. 取值仍归 application.yml, 规则归代码.
 */
@Data
@Component
@ConfigurationProperties(prefix = "anitrack.ranking")
public class RankingProperties {

    /** 先验票数 m: 票数正好等于它时, 条目自己的评分与先验各占一半的权重 */
    private double priorVotes = 200.0;

    /** 先验分数 C: 零票条目的得分, 也是所有小样本被拉向的那条"及格线" */
    private double priorScore = 7.0;
}
